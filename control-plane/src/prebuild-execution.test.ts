import assert from "node:assert/strict";
import test from "node:test";
import { readFile, readdir } from "node:fs/promises";
import pg from "pg";
import { createHash } from "node:crypto";

test("clean prebuild lifecycle and durable scoped executions", { skip: !process.env.CONTROL_PLANE_TEST_DATABASE_URL }, async () => {
  const admin = new pg.Client({ connectionString: process.env.CONTROL_PLANE_TEST_DATABASE_URL });
  await admin.connect();
  const schema = `qa_execution_${crypto.randomUUID().replaceAll("-", "")}`;
  const url = new URL(process.env.CONTROL_PLANE_TEST_DATABASE_URL!);
  url.searchParams.set("options", `-c search_path=${schema}`);
  Object.assign(process.env, {
    DATABASE_URL: url.toString(), BETTER_AUTH_URL: "http://localhost:3098", BETTER_AUTH_SECRET: "local-test-auth-secret-000000000000",
    SECRET_ENCRYPTION_KEYS: "test=AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=", PREVIEW_TOKEN_SECRET: "local-test-preview-secret-000000000",
    TERMINAL_TOKEN_SECRET: "local-test-terminal-secret-000000000", SSH_TOKEN_SECRET: "local-test-ssh-secret-00000000000000",
    COMPUTE_AGENT_TOKEN: "local-test-compute-secret-000000000", MANAGED_COMPUTE_NODE_ID: "node-a",
  });
  await admin.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
  const { db } = await import("./db.js");
  try {
    const migrations = new URL("../migrations/", import.meta.url);
    for (const name of (await readdir(migrations)).filter(name => name.endsWith(".sql")).sort()) await admin.query(await readFile(new URL(name, migrations), "utf8"));
    await admin.query(`INSERT INTO "user" (id,name,email,"emailVerified") VALUES ('user','User','execution@example.test',true);
      INSERT INTO organizations (id,name,slug,hosting_mode) VALUES ('org','Org','org','managed'), ('other','Other','other','managed');
      INSERT INTO memberships(id,organization_id,user_id,role) VALUES ('admin-org','org','user','admin'),('admin-other','other','user','admin');`);
    await admin.query("UPDATE billing_accounts SET complimentary=true WHERE organization_id IN ('org','other')");
    const actor = { organizationId: "org", organizationName: "Org", organizationSlug: "org", actorUserId: "user", automationIdPrefix: null };
    const foreign = { ...actor, organizationId: "other" };
    const scoped = { ...actor, automationIdPrefix: "github:other:" };
    const prebuilds = await import("./prebuilds.js");
    const executions = await import("./executions.js");
    const environments = await import("./environment-service.js");
    const { Hono } = await import("hono");
    const { registerComputeRoutes } = await import("./compute.js");
    const app = new Hono<import("./types.js").AppEnv>();
    app.use("*", async (c,next) => { c.set("requestId",crypto.randomUUID()); await next(); });
    registerComputeRoutes(app);
    const { registerPublicApiRoutes } = await import("./public-api.js");
    registerPublicApiRoutes(app);
    const keyId = `key_${"a".repeat(32)}`, keySecret = "b".repeat(43);
    await admin.query("INSERT INTO api_keys (id,organization_id,name,secret_hash,secret_prefix,scopes,created_by_user_id) VALUES ($1,'org','Local test',$2,'local',ARRAY['read','write','delete'],'user')", [keyId,createHash("sha256").update(keySecret).digest("hex")]);
    async function api(path: string, body?: object, headers: Record<string,string> = {}) {
      return app.request(`/v1${path}`, { method: body === undefined ? "GET" : "POST", headers: {authorization:`Bearer dvk_live_${keyId}.${keySecret}`,"content-type":"application/json",...headers}, ...(body === undefined ? {} : {body:JSON.stringify(body)}) });
    }
    async function post(path: string, body: object) {
      return app.request(`/api/compute/${path}`, { method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${process.env.COMPUTE_AGENT_TOKEN}` }, body: JSON.stringify({ node_id: "node-a", ...body }) });
    }
    const template = { image: "driftverk-dev:1", setup_command: "npm ci", initialization_command: "npm run seed", startup_command: "npm run dev", readiness_command: "curl -f localhost:3000", environment_variables: [{ name: "SECRET", value: "must-not-copy" }], volume_mounts: [{ volume_id: "private", mount_path: "/data" }] };
    await admin.query("INSERT INTO environment_templates (id,organization_id,name,configuration) VALUES ('template','org','Project',$1)", [JSON.stringify(template)]);
    await assert.rejects(prebuilds.createPrebuild(foreign, "template"), /not found/);
    await assert.rejects(prebuilds.createPrebuild(scoped, "template"), /Repository-scoped/);
    const prebuild = await prebuilds.createPrebuild(actor, "template");
    assert.equal((await prebuilds.createPrebuild(actor, "template")).id, prebuild.id, "concurrent requests share the active build");
    const saved = (await admin.query("SELECT * FROM project_prebuilds WHERE id=$1", [prebuild.id])).rows[0];
    const builder = (await admin.query("SELECT * FROM sandboxes WHERE id=$1", [saved.sandbox_id])).rows[0];
    assert.equal(builder.purpose, "prebuild");
    assert.equal(builder.has_ever_received_environment_secrets, false, "fresh builder is eligible for clean snapshot capture");
    assert.equal(builder.initialization_command, null);
    assert.equal(builder.startup_command, null);
    assert.equal(builder.readiness_command, null);
    assert.equal(JSON.stringify(saved.configuration).includes("must-not-copy"), false);
    assert.equal((await admin.query("SELECT * FROM sandbox_environment_variables WHERE sandbox_id=$1", [builder.id])).rowCount, 0);
    assert.equal((await admin.query("SELECT * FROM sandbox_volume_mounts WHERE sandbox_id=$1", [builder.id])).rowCount, 0);
    assert.equal((await environments.listEnvironmentsForActor(actor)).length, 0, "builder is hidden from daily environments");
    await assert.rejects(prebuilds.resolvePrebuild("org", { prebuild_id: prebuild.id }), /not ready/);
    assert.equal((await post("jobs/claim", { capabilities: ["development-setup-v1", "project-readiness-v1"] })).status, 204);
    const claim = await post("jobs/claim", { capabilities: ["development-setup-v1", "project-readiness-v1", "prebuilds-v1"] });
    assert.equal(claim.status, 200, await claim.clone().text());
    const claimed = await claim.json();
    assert.equal(claimed.sandbox.snapshot_allowed, true, "runtime receives snapshot eligibility for the secret-free builder");
    const job = claimed.job;
    const finished = await post(`jobs/${job.id}/events`, { event: "succeeded", runtime_id: "deleted-builder", artifact_ref: "driftverk/prebuild:ready", snapshot_size_gb: 0.1 });
    assert.equal(finished.status, 200, await finished.clone().text());
    assert.equal((await admin.query("SELECT state,runtime_id FROM sandboxes WHERE id=$1", [builder.id])).rows[0].state, "deleted");
    assert.equal((await prebuilds.listPrebuilds(actor))[0].status, "ready");
    await assert.rejects(prebuilds.resolvePrebuild("other", { prebuild_id: prebuild.id }), /not ready/);
    const resolved = await prebuilds.resolvePrebuild("org", { prebuild_id: prebuild.id, setup_command: "evil override" });
    assert.equal(resolved.setup_command, null);
    assert.equal(resolved.initialization_command, "npm run seed");
    const restored = await environments.createEnvironmentForActor(actor, { prebuild_id: prebuild.id, code_trust: "trusted", environment_variables: [{ name: "SECRET", value: "runtime-only" }] });
    const envId = restored.environment_id;
    const storedVariable = (await admin.query("SELECT encrypted_value FROM sandbox_environment_variables WHERE sandbox_id=$1", [envId])).rows[0];
    assert.ok(storedVariable);
    assert.notEqual(storedVariable.encrypted_value, "runtime-only");
    await admin.query("UPDATE compute_jobs SET status='succeeded' WHERE sandbox_id=$1;", [envId]);
    await admin.query("UPDATE sandboxes SET state='running',runtime_id='runtime',compute_node_id='node-a' WHERE id=$1", [envId]);
    async function execute(input: Record<string, unknown> = { command: "echo hello", artifacts: ["result.bin"] }, identity = actor) {
      const client = await db.connect();
      try { await client.query("BEGIN"); const result = await executions.createExecution(identity,envId,input,client); await client.query("COMMIT"); return result; }
      catch (error) { await client.query("ROLLBACK"); throw error; } finally { client.release(); }
    }
    await assert.rejects(execute({ command: "true" }, foreign), /not found/);
    await assert.rejects(execute({ command: "true", artifacts: ["../secret"] }), /artifact paths/);
    const requestHeaders = {"Idempotency-Key":"execution-test-key"};
    const executionInput = {command:"echo hello",artifacts:["result.bin"],environment_variables:[{name:"PREVIEW_GITHUB_TOKEN",value:"test-execution-secret"}]};
    const created = await api(`/environments/${envId}/executions`,executionInput,requestHeaders);
    assert.equal(created.status,202,await created.clone().text());
    const execution = (await created.json()).data;
    const secretRow = (await admin.query("SELECT encrypted_environment, environment_iv FROM sandbox_executions WHERE id=$1", [execution.id])).rows[0];
    assert.ok(secretRow.encrypted_environment && secretRow.environment_iv);
    assert.equal(JSON.stringify(secretRow).includes("test-execution-secret"), false);
    assert.equal(JSON.stringify(await executions.getExecution(actor,execution.id)).includes(secretRow.encrypted_environment), false);
    assert.equal(JSON.stringify((await admin.query("SELECT * FROM api_idempotency_keys")).rows).includes("test-execution-secret"), false);
    const replay = await api(`/environments/${envId}/executions`,executionInput,requestHeaders);
    assert.equal(replay.status,202);
    assert.equal((await replay.json()).data.id,execution.id,"HTTP retry retains the execution ID");
    assert.equal((await api(`/environments/${envId}/executions`,{command:"different"},requestHeaders)).status,409,"idempotency key rejects a different command");
    await assert.rejects(execute(), /already active/);
    await assert.rejects(environments.changeEnvironmentStateForActor(actor,envId,"stop"), /active execution/);
    await assert.rejects(executions.getExecution(foreign, execution.id), /not found/);
    await assert.rejects(executions.getExecution(scoped, execution.id), /not found/);
    const polled = await post("executions/poll", {});
    assert.equal(polled.status, 200, await polled.clone().text());
    const polledExecution = (await polled.json()).executions[0];
    assert.equal(polledExecution.id, execution.id);
    assert.equal(polledExecution.environment_variables.PREVIEW_GITHUB_TOKEN, "test-execution-secret");
    const chunk = { status: "running", stdout: { offset: 0, data: Buffer.from("hello\n").toString("base64") }, stderr: { offset: 0, data: Buffer.from("warning\n").toString("base64") } };
    assert.equal((await post(`executions/${execution.id}/report`, chunk)).status, 200);
    assert.equal((await post(`executions/${execution.id}/report`, chunk)).status, 200, "lost acknowledgement may replay safely");
    const output = await executions.executionOutput(actor,execution.id);
    assert.equal(output.length, 2);
    assert.equal(Buffer.from(output[0].data,"base64").toString(), "hello\n");
    assert.equal((await executions.executionOutput(actor,execution.id,output[0].sequence)).length, 1);
    assert.equal((await post(`executions/${execution.id}/report`, { stdout: { offset: 99, data: "YQ==" } })).status, 409);
    const foreignNode = new Hono<import("./types.js").AppEnv>();
    foreignNode.use("*",async(c,next)=>{c.set("computeAgent",{id:"node-a",organizationId:"other",managed:false});await next();});
    foreignNode.post("/poll",executions.pollExecutions);
    foreignNode.post("/:id/report",executions.reportExecution);
    assert.equal((await (await foreignNode.request("/poll",{method:"POST"})).json()).executions.length,0,"same node ID cannot cross organization boundary");
    assert.equal((await foreignNode.request(`/${execution.id}/report`,{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify(chunk)})).status,404);
    const binary = Buffer.from([0,1,255]);
    assert.equal((await post(`executions/${execution.id}/report`, { status: "failed", exit_code: 7, artifacts: [{ path: "result.bin", data: binary.toString("base64") }] })).status, 200);
    assert.equal((await executions.getExecution(actor,execution.id)).exit_code, 7);
    assert.deepEqual((await admin.query("SELECT encrypted_environment, environment_iv FROM sandbox_executions WHERE id=$1", [execution.id])).rows[0], {encrypted_environment:null,environment_iv:null}, "terminal transitions erase stored execution secrets");
    assert.deepEqual(await executions.executionArtifact(actor,execution.id,"result.bin"), binary);
    await assert.rejects(executions.executionArtifact(foreign,execution.id,"result.bin"), /not found/);
    const sse = await api(`/executions/${execution.id}/events`,undefined,{"Last-Event-ID":output[0].sequence});
    assert.equal(sse.status,200);
    const events = await sse.text();
    assert.equal((events.match(/event: output/g)||[]).length,1,"SSE reconnect emits only the remaining output");
    assert.match(events,/event: done/);
    assert.match(events,/"exit_code":7/);
    const artifactResponse = await api(`/executions/${execution.id}/artifact?path=result.bin`);
    assert.equal(artifactResponse.headers.get("content-type"),"application/octet-stream");
    assert.deepEqual(Buffer.from(await artifactResponse.arrayBuffer()),binary);
    const {environmentTasks}=await import('./environment-tasks.js');
    const review=new Hono<import('./types.js').AppEnv>();
    let reviewUser='user';
    review.on(['GET','POST'],'/environments/:id/tasks',c=>environmentTasks(c,{user:{id:reviewUser},session:{activeOrganizationId:'org'}} as never));
    const taskPath=`/environments/${envId}/tasks`;
    const history=await review.request(taskPath);
    assert.equal(history.status,200);
    assert.equal((await history.json()).executions[0].id,execution.id);
    const result=await (await review.request(`${taskPath}?execution=${execution.id}`)).json();
    assert.equal(result.execution.exit_code,7);
    assert.equal(Buffer.from(result.output[0].data,'base64').toString(),'hello\n');
    assert.equal((await review.request(`/environments/not-this-environment/tasks?execution=${execution.id}`)).status,404);
    const download=await review.request(`${taskPath}?execution=${execution.id}&artifact=result.bin`);
    assert.match(download.headers.get('content-disposition') || '',/attachment; filename="result.bin"/);
    assert.deepEqual(Buffer.from(await download.arrayBuffer()),binary);
    await admin.query(`INSERT INTO "user"(id,name,email,"emailVerified") VALUES('review-member','Member','review@example.test',true);
      INSERT INTO memberships(id,organization_id,user_id,role) VALUES('review-member','org','review-member','member')`);
    reviewUser='review-member';
    assert.equal((await review.request(taskPath)).status,404,'unassigned member cannot review output');
    reviewUser='user';
    const queued = await execute({command:"sleep 20"});
    assert.equal((await executions.cancelExecution(actor,queued.id)).status,"cancelled");
    assert.equal((await (await post("executions/poll",{})).json()).executions.length,0);
    const running = await execute({command:"sleep 20"});
    await post("executions/poll",{});
    assert.equal((await executions.cancelExecution(actor,running.id)).status,"running");
    assert.equal((await (await post("executions/poll",{})).json()).executions[0].cancel_requested,true);
    assert.equal((await post(`executions/${running.id}/report`,{status:"cancelled",exit_code:-9})).status,200);
    await executions.deleteExecution(actor,running.id);
    await assert.rejects(executions.getExecution(actor,running.id),/not found/);
    const interrupted = await execute({command:"sleep 20"});
    await post("executions/poll",{});
    const removal = await environments.changeEnvironmentStateForActor(actor,envId,"delete");
    assert.equal(removal.status,"queued","deletion remains available while execution is active");
    assert.equal((await executions.getExecution(actor,interrupted.id)).cancel_requested,true);
    const cleanupClaim = await post("jobs/claim",{capabilities:["development-setup-v1","project-readiness-v1","prebuilds-v1"]});
    assert.equal(cleanupClaim.status,200,await cleanupClaim.clone().text());
    assert.equal((await cleanupClaim.json()).job.id,removal.operation_id);
    assert.equal((await post(`jobs/${removal.operation_id}/events`,{event:"succeeded"})).status,200);
    assert.equal((await executions.getExecution(actor,interrupted.id)).status,"cancelled","successful deletion finalizes the active execution");
    assert.equal((await admin.query("SELECT state FROM sandboxes WHERE id=$1",[envId])).rows[0].state,"deleted");
    const failedPrebuild = await prebuilds.createPrebuild(actor,"template");
    const buildClaim = await post("jobs/claim",{capabilities:["development-setup-v1","project-readiness-v1","prebuilds-v1"]});
    assert.equal(buildClaim.status,200,await buildClaim.clone().text());
    const failedJob = (await buildClaim.json()).job;
    assert.equal((await post(`jobs/${failedJob.id}/events`,{event:"failed",error:"setup failed"})).status,200);
    const failed = (await admin.query("SELECT * FROM project_prebuilds WHERE id=$1",[failedPrebuild.id])).rows[0];
    assert.equal(failed.status,"failed");
    assert.equal((await admin.query("SELECT status FROM workspace_snapshots WHERE id=$1",[failed.snapshot_id])).rows[0].status,"failed");
    const builderCleanup = (await admin.query("SELECT id,operation,status FROM compute_jobs WHERE sandbox_id=$1 AND status='queued'",[failed.sandbox_id])).rows[0];
    assert.equal(builderCleanup.operation,"delete","failed builder is queued for physical cleanup");
    const cleanup = await post("jobs/claim",{});
    assert.equal(cleanup.status,200,await cleanup.clone().text());
    assert.equal((await cleanup.json()).job.id,builderCleanup.id);
    assert.equal((await post(`jobs/${builderCleanup.id}/events`,{event:"succeeded"})).status,200);
    assert.equal((await admin.query("SELECT state FROM sandboxes WHERE id=$1",[failed.sandbox_id])).rows[0].state,"deleted");
    assert.deepEqual(await executions.executionArtifact(actor,execution.id,"result.bin"),binary,"retained output survives environment cleanup");
  } finally {
    await db.end();
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  }
});
