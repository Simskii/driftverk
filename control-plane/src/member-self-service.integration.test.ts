import assert from "node:assert/strict";
import test from "node:test";
import { Hono } from "hono";
import type { AppEnv } from "./types.js";

test("member quota, permissions, defaults, concurrency and revocation", { skip: !process.env.CONTROL_PLANE_TEST_DATABASE_URL }, async () => {
  const schema = `member_creation_${crypto.randomUUID().replaceAll("-", "")}`;
  const url = new URL(process.env.CONTROL_PLANE_TEST_DATABASE_URL!);
  url.searchParams.set("options", `-csearch_path=${schema}`);
  Object.assign(process.env, { DATABASE_URL: url.href, BETTER_AUTH_URL: "http://localhost:3000", BETTER_AUTH_SECRET: "test-auth-secret-0000000000000000", SECRET_ENCRYPTION_KEYS: "test=AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=", PREVIEW_TOKEN_SECRET: "test-preview-secret-0000000000000", TERMINAL_TOKEN_SECRET: "test-terminal-secret-000000000000", SSH_TOKEN_SECRET: "test-ssh-secret-000000000000000000", COMPUTE_AGENT_TOKEN: "test-compute-secret-0000000000000" });
  const { db } = await import("./db.js");
  const { migrate } = await import("./migrate.js");
  const { createEnvironment, environmentAction, getEnvironment } = await import("./workspace.js");
  const { requireEnvironmentAccess, hasEnvironmentAccess } = await import("./environment-access.js");
  const { memberCreationSettings } = await import("./member-self-service.js");
  const app = new Hono<AppEnv>();
  app.use("*", async (c,next) => { c.set("authSession", { user:{id:c.req.header("x-user") || "member"}, session:{activeOrganizationId:"org"} } as never); await next(); });
  app.post("/environments", c => createEnvironment(c,c.get("authSession")));
  app.use("/environments/:id",requireEnvironmentAccess); app.use("/environments/:id/*",requireEnvironmentAccess);
  app.post("/environments/:id/actions",c => environmentAction(c,c.get("authSession")));
  app.get("/environments/:id",c => getEnvironment(c,c.get("authSession")));
  app.get("/settings",memberCreationSettings); app.put("/settings",memberCreationSettings);
  const request = (path:string,body?:object,user="member",method="POST") => app.request(path,{method,headers:{"content-type":"application/json","x-user":user},...(body ? {body:JSON.stringify(body)} : {})});
  const create = (body:object,user?:string) => request('/environments',body,user);
  const action = (id:string,action:string,user?:string) => request(`/environments/${id}/actions`,{action},user);
  try {
    await db.query(`CREATE SCHEMA ${schema}`); await migrate();
    await db.query(`INSERT INTO "user"(id,name,email,"emailVerified") VALUES ('admin','Admin','admin@member.test',true),('member','Member','member@member.test',true),('other','Other','other@member.test',true);
      INSERT INTO organizations(id,name,slug) VALUES ('org','QA','qa');
      INSERT INTO memberships(id,organization_id,user_id,role) VALUES ('ma','org','admin','admin'),('mm','org','member','member'),('mo','org','other','member');
      UPDATE billing_accounts SET complimentary=true WHERE organization_id='org';`);
    for (const input of [{image:'custom:1'},{cpu:8},{source_type:'snapshot',snapshot_id:'private'},{organization_secret_names:['SECRET']},{agent_id:'codex'},{volume_mounts:[]},{personal_owner_user_id:'other'}]) assert.equal((await create(input)).status,403,JSON.stringify(input));
    const settings = await (await request('/settings',undefined,'member','GET')).json();
    const assigned = await create({name:'assigned',image:settings.image},'admin'); assert.equal(assigned.status,202);
    const assignedId = (await assigned.json()).id;
    await db.query("INSERT INTO environment_members(sandbox_id,membership_id) VALUES ($1,'mm')",[assignedId]);
    const results = await Promise.all([create({name:'one'}),create({name:'two'})]);
    assert.deepEqual(results.map(r=>r.status).sort(),[202,409]);
    const id = (await results.find(r=>r.status===202)!.json()).id;
    await assert.rejects(db.query("UPDATE sandboxes SET personal_owner_user_id='member' WHERE id=$1",[assignedId]), {code:'23505'});
    assert.equal(await hasEnvironmentAccess(id,'member'),true); assert.equal(await hasEnvironmentAccess(id,'other'),false);
    const detail = await (await request(`/environments/${id}`,undefined,'member','GET')).json();
    assert.equal(detail.environment.can_manage_actions,true); assert.equal(detail.environment.can_manage_configuration,false);
    assert.equal((await action(assignedId,'delete')).status,403); assert.equal((await action(id,'delete','other')).status,404);
    const ready = async (state:string) => { await db.query("UPDATE compute_jobs SET status='succeeded' WHERE sandbox_id=$1",[id]); await db.query("UPDATE sandboxes SET state=$2,desired_state=$2 WHERE id=$1",[id,state]); };
    await ready('stopped'); assert.equal((await create({name:'three'})).status,409);
    assert.equal((await action(id,'start')).status,202);
    await ready('running'); assert.equal((await action(id,'stop')).status,202);
    await ready('stopped'); assert.equal((await action(id,'delete')).status,202);
    assert.equal((await create({name:'three'})).status,409);
    await ready('deleted');
    const policy = (enabled:boolean,user='admin') => request('/settings',{enabled,cpu:2,memory_mb:4096},user,'PUT');
    assert.equal((await policy(false,'member')).status,403); assert.equal((await policy(false)).status,200);
    assert.equal((await create({name:'three'})).status,403); assert.equal((await policy(true)).status,200);
    const replacement = await create({name:'three'}); assert.equal(replacement.status,202);
    const nextId = (await replacement.json()).id;
    assert.deepEqual((await db.query('SELECT cpu_count,memory_mb FROM sandboxes WHERE id=$1',[nextId])).rows[0],{cpu_count:2,memory_mb:4096});
    await db.query("DELETE FROM environment_members WHERE sandbox_id=$1 AND membership_id='mm'",[nextId]);
    assert.equal((await action(nextId,'delete')).status,404); assert.equal((await create({name:'four'})).status,409);
    await db.query("DELETE FROM memberships WHERE id='mm'"); assert.equal((await create({name:'four'})).status,403);
  } finally { await db.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); await db.end(); }
});
